-- 腾讯位置服务 POI 补全与人工核验留痕。基地正式地址仍只保存在 education_bases。
create table if not exists public.education_base_location_reviews (
  id bigint generated by default as identity primary key,
  base_id bigint not null unique references public.education_bases(id) on delete cascade,
  search_query text not null,
  status text not null default 'needs_review' check (status in ('auto_matched', 'needs_review', 'not_found', 'confirmed', 'manual_confirmed', 'failed')),
  selected_candidate_id bigint,
  last_error text,
  searched_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.education_base_location_candidates (
  id bigint generated by default as identity primary key,
  review_id bigint not null,
  poi_id text,
  candidate_rank smallint not null check (candidate_rank between 1 and 5),
  poi_name text not null,
  address text,
  latitude double precision,
  longitude double precision,
  city text,
  district text,
  poi_category text,
  name_similarity double precision not null default 0,
  city_match boolean not null default false,
  district_match boolean not null default false,
  match_score smallint not null default 0 check (match_score between 0 and 100),
  confidence_level text not null default 'low',
  is_reasonable_category boolean not null default false,
  created_at timestamptz not null default now(),
  unique (review_id, candidate_rank)
);

-- 允许在预发布环境重复执行：如果表曾由较早草稿创建，补齐评分字段。
alter table public.education_base_location_candidates add column if not exists city_match boolean not null default false;
alter table public.education_base_location_candidates add column if not exists district_match boolean not null default false;
alter table public.education_base_location_candidates add column if not exists confidence_level text not null default 'low';

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'education_base_location_candidates_confidence_check') then
    alter table public.education_base_location_candidates
      add constraint education_base_location_candidates_confidence_check
      check (confidence_level in ('high', 'medium', 'low'));
  end if;
  if not exists (
    select 1 from pg_constraint
    where contype = 'f'
      and conrelid = 'public.education_base_location_candidates'::regclass
      and confrelid = 'public.education_base_location_reviews'::regclass
  ) then
    alter table public.education_base_location_candidates
      add constraint education_base_location_candidates_review_fk
      foreign key (review_id) references public.education_base_location_reviews(id) on delete cascade;
  end if;
  if not exists (
    select 1 from pg_constraint
    where contype = 'f'
      and conrelid = 'public.education_base_location_reviews'::regclass
      and confrelid = 'public.education_base_location_candidates'::regclass
  ) then
    alter table public.education_base_location_reviews
      add constraint education_base_location_reviews_selected_candidate_fk
      foreign key (selected_candidate_id) references public.education_base_location_candidates(id) on delete set null;
  end if;
end $$;

create index if not exists education_base_location_candidates_review_rank_idx
  on public.education_base_location_candidates (review_id, candidate_rank);

alter table public.education_base_location_reviews enable row level security;
alter table public.education_base_location_candidates enable row level security;

create or replace function public.touch_education_base_location_reviews_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists education_base_location_reviews_touch_updated_at on public.education_base_location_reviews;
create trigger education_base_location_reviews_touch_updated_at
before update on public.education_base_location_reviews
for each row execute function public.touch_education_base_location_reviews_updated_at();

